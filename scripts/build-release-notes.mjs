// Compiles docs/release-notes/*.md into src/app/core/release-notes.generated.ts.
// Runs automatically via the `prebuild`/`prestart` npm hooks; run it directly
// with `npm run notes:build`.
//
// The markdown files are the ONLY place release notes are authored. This
// script parses them into structured data (section → bullet → lead + text) so
// the app renders them with real components instead of shipping a markdown
// parser or dumping [innerHTML].
//
// Authoring format (see docs/release-notes/README.md):
//
//   docs/release-notes/0009-social-slots.md   ← NNNN prefix is the `seq`
//   ---
//   version: 0.9
//   date: 2026-07-26
//   title: Social slots
//   summary: One sentence shown in the What's-new list.
//   ---
//
//   ## Added
//   - **Bold lead** — what it does, in plain language.
//
// Recognised sections: Added / Changed / Fixed / Removed. Bullets should use
// the "**lead** — description" shape; a bullet without a bold lead is fine
// and renders as a plain line.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const SRC_DIR = 'docs/release-notes';
const OUT = 'src/app/core/release-notes.generated.ts';
const SECTIONS = ['Added', 'Changed', 'Fixed', 'Removed'];

const fail = (msg) => {
  console.error(`[release-notes] ${msg}`);
  process.exit(1);
};

/** `- **Lead** — text` → { lead, text }; anything else → { lead: null, text }. */
function parseBullet(raw) {
  const line = raw.replace(/\s+/g, ' ').trim();
  const m = line.match(/^\*\*(.+?)\*\*\s*[—–-]\s*(.*)$/);
  const clean = (s) => s.replace(/\*\*/g, '').replace(/`/g, '').trim();
  return m
    ? { lead: clean(m[1]), text: clean(m[2]) }
    : { lead: null, text: clean(line) };
}

function parseNote(file) {
  const seqMatch = file.match(/^(\d{4})-/);
  if (!seqMatch) fail(`${file}: filename must start with a 4-digit sequence, e.g. 0010-name.md`);
  const seq = Number(seqMatch[1]);

  const body = readFileSync(`${SRC_DIR}/${file}`, 'utf8').replace(/\r\n/g, '\n');
  const fm = body.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!fm) fail(`${file}: missing --- frontmatter block`);

  const meta = {};
  for (const line of fm[1].split('\n')) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].trim();
  }
  for (const key of ['version', 'date', 'title', 'summary']) {
    if (!meta[key]) fail(`${file}: frontmatter is missing "${key}"`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) fail(`${file}: date must be YYYY-MM-DD`);

  const sections = [];
  let current = null;
  let pending = null;
  const flush = () => {
    if (pending !== null && current) current.items.push(parseBullet(pending));
    pending = null;
  };

  for (const line of fm[2].split('\n')) {
    const heading = line.match(/^##\s+(.+?)\s*$/);
    if (heading) {
      flush();
      if (!SECTIONS.includes(heading[1])) {
        fail(`${file}: unknown section "${heading[1]}" (use ${SECTIONS.join(' / ')})`);
      }
      current = { heading: heading[1], items: [] };
      sections.push(current);
      continue;
    }
    const bullet = line.match(/^[-*]\s+(.*)$/);
    if (bullet) {
      flush();
      pending = bullet[1];
      continue;
    }
    // indented continuation of the bullet above
    if (pending !== null && /^\s+\S/.test(line)) pending += ' ' + line.trim();
    else flush();
  }
  flush();

  const kept = sections.filter((s) => s.items.length);
  if (!kept.length) fail(`${file}: no bullets found under any section`);

  return { seq, version: meta.version, date: meta.date, title: meta.title, summary: meta.summary, sections: kept };
}

const files = readdirSync(SRC_DIR)
  .filter((f) => f.endsWith('.md') && f !== 'README.md')
  .sort();
if (!files.length) fail(`no release notes found in ${SRC_DIR}`);

const notes = files.map(parseNote).sort((a, b) => b.seq - a.seq); // newest first

const seen = new Set();
for (const n of notes) {
  if (seen.has(n.seq)) fail(`duplicate sequence ${n.seq} — every note needs its own NNNN prefix`);
  seen.add(n.seq);
}

const s = (v) => JSON.stringify(v);
const body = notes
  .map(
    (n) => `  {
    seq: ${n.seq},
    version: ${s(n.version)},
    date: ${s(n.date)},
    title: ${s(n.title)},
    summary: ${s(n.summary)},
    sections: [
${n.sections
  .map(
    (sec) => `      {
        heading: ${s(sec.heading)},
        items: [
${sec.items.map((i) => `          { lead: ${s(i.lead)}, text: ${s(i.text)} },`).join('\n')}
        ],
      },`,
  )
  .join('\n')}
    ],
  },`,
  )
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/build-release-notes.mjs — do not edit by hand.
// Source of truth: docs/release-notes/*.md · rebuild with \`npm run notes:build\`.
import type { ReleaseNote } from './release-notes';

/** Newest first. */
export const RELEASE_NOTES: readonly ReleaseNote[] = [
${body}
];

/** Highest sequence in this build — compared against profiles.last_seen_release_seq. */
export const LATEST_RELEASE_SEQ = ${notes[0].seq};
`,
);

console.log(
  `[release-notes] ${OUT} written — ${notes.length} notes, latest v${notes[0].version} (seq ${notes[0].seq})`,
);
